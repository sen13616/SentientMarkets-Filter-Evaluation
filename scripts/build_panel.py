"""Phase 1: daily state panel, used universe, snapshot hashes and results/coverage.md.

Uses sentiment ticks and the presence of price bars only; no returns are computed.
"""

import json
import sys
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from filter_eval import prices  # noqa: E402
from filter_eval.config import DATA, FIRST_DECISION, INPUT_INDICES, RESULTS, WINDOW_END, WINDOW_START  # noqa: E402
from filter_eval.ingest import MANIFEST, frame_hash, load_manifest, load_ticks  # noqa: E402
from filter_eval.panel import build_state_panel, label_band, window_sessions  # noqa: E402
from filter_eval.universe import candidates, used_universe  # noqa: E402

PANEL = DATA / "panel" / "states.parquet"
SNAPSHOT = RESULTS / "snapshot.json"
BANDS = ["Strongly Bearish", "Bearish", "Neutral", "Bullish", "Strongly Bullish"]


def pct(x):
    return f"{100 * x:.1f}%"


def md_table(df: pd.DataFrame, index=True) -> str:
    return df.to_markdown(index=index)


def main():
    cands = candidates()
    man = load_manifest(MANIFEST)
    ok = [t for t in cands if man["tickers"].get(t, {}).get("status") == "ok"]
    not_ok = sorted(set(cands) - set(ok))
    if not_ok:
        print("WARNING: candidates without a successful pull:", not_ok)
    ticks = load_ticks(ok)
    sessions = window_sessions()
    panel = build_state_panel(ticks, cands, sessions)

    px = prices.load()
    pxw = px[px["date"].isin(set(sessions))]
    bars = pxw.dropna(subset=["open", "close"]).groupby("ticker")["date"].nunique()
    price_ok = bars.reindex(cands).fillna(0).eq(len(sessions))
    uu = used_universe(panel, price_ok, sessions)
    uu["has_ticks"] = uu["ticker"].isin(set(ticks["ticker"]))
    used = sorted(uu.loc[uu["used"], "ticker"])

    # Persist: panel (data/, ignored), universe list and hashes (results/, committed).
    PANEL.parent.mkdir(parents=True, exist_ok=True)
    panel.to_parquet(PANEL, index=False)
    uu.to_csv(RESULTS / "universe_candidates.csv", index=False)
    pd.Series(used, name="ticker").to_csv(RESULTS / "used_universe.csv", index=False)
    pman = json.loads(prices.PRICE_MANIFEST.read_text())
    tick_hash = frame_hash(ticks, ["ticker", "ts"])
    state_cols = ["ticker", "day", "ts", "score", "score_raw", "confidence", "market", "narrative",
                  "influencer", "macro", "score_exo", "div_spread"]
    panel_hash = frame_hash(panel[state_cols].assign(day=panel["day"].astype(str)), ["ticker", "day"])
    snap = {
        "sentiment_ticks_sha256": tick_hash, "state_panel_sha256": panel_hash,
        "prices_sha256": pman["content_sha256"], "price_download_utc": pman["download_utc"],
        "price_source": pman["source"], "sentiment_pull_completed_utc": man.get("completed_at"),
        "sentiment_days_param": man.get("days_param"), "n_candidates": len(cands),
        "n_used": len(used), "n_ticks": int(len(ticks)),
        "rows_discarded_after_lock": int(sum(e.get("rows_discarded", 0) for e in man["tickers"].values()
                                             if e.get("status") == "ok")),
    }
    SNAPSHOT.write_text(json.dumps(snap, indent=1))
    print(json.dumps(snap, indent=1))
    print(f"used universe: {len(used)}")

    # ------------------------------------------------------------------ coverage
    U = panel[panel["ticker"].isin(used)].copy()
    lines = ["# Coverage report (research window)", "",
             "Generated by `scripts/build_panel.py` from stored sentiment ticks and the presence of "
             "price bars. No return data is used.", ""]
    lines += ["## Window and sessions", "",
              f"- Window: {WINDOW_START} to {WINDOW_END}; NYSE sessions (XNYS calendar): **{len(sessions)}**.",
              f"- First decision session: {FIRST_DECISION} (no ticker has a state on {WINDOW_START}; D4).",
              ]
    weekdays = pd.bdate_range(WINDOW_START, WINDOW_END).date
    non_sessions = [d for d in weekdays if d not in set(sessions)]
    tick_days = ticks["ts"].dt.date.value_counts()
    for d in non_sessions:
        lines.append(f"- {d} ({pd.Timestamp(d).day_name()}) is a weekday but not an NYSE session: "
                     f"{int(tick_days.get(d, 0)):,} ticks exist that day and none is used as a state.")
    lines.append(f"- Holiday check: 2026-05-25 in sessions = {date(2026, 5, 25) in sessions}; "
                 f"2026-06-19 in sessions = {date(2026, 6, 19) in sessions}.")
    lines.append("")

    lines += ["## Used universe", ""]
    steps = [("Candidates from seed_universe.csv (D7)", len(cands)),
             ("with a successful sentiment pull", len(ok)),
             ("with at least one stored tick", int(uu["has_ticks"].sum())),
             ("with a price bar on every window session", int((uu["has_ticks"] & uu["price_ok"]).sum())),
             ("and valid state on >= 90% of sessions", int((uu["has_ticks"] & uu["price_ok"] & (uu["valid_share"] >= 0.9)).sum())),
             ("and a valid state in the first five and last five sessions (= used universe)", len(used))]
    lines += [md_table(pd.DataFrame(steps, columns=["Step", "Names"]), index=False), ""]
    no_px = sorted(uu.loc[~uu["price_ok"], "ticker"])
    lines.append(f"- Dropped for lack of yfinance bars on every window session ({len(no_px)}): "
                 f"{', '.join(no_px) if no_px else 'none'}. yfinance returned no data at all for: "
                 f"{', '.join(pman['no_data']) or 'none'}.")
    cov_fail = uu[uu["has_ticks"] & uu["price_ok"] & ~uu["used"]]
    if len(cov_fail):
        cf = cov_fail[["ticker", "valid_share", "valid_first5", "valid_last5"]].copy()
        cf["valid_share"] = cf["valid_share"].map(pct)
        lines += [f"- Dropped by the sentiment coverage rule ({len(cf)}):", "", md_table(cf, index=False), ""]
    else:
        lines.append("- Dropped by the sentiment coverage rule: none.")
    lines.append("")

    lines += ["## Missing state by session (used universe)", "",
              "A state is valid when a tick before 21:45 UTC exists and `score_exo` and `confidence` "
              "are defined (D10).", ""]
    by_day = U.groupby("day").agg(names=("ticker", "size"), valid=("state_valid", "sum"))
    by_day["missing_share"] = (1 - by_day["valid"] / by_day["names"]).map(pct)
    lines += [md_table(by_day[["valid", "missing_share"]]), ""]

    lines += ["## State distribution by input index (used universe, all window sessions)", "",
              "Bands apply to the half-up rounded index (D11). `composite` is the served smoothed "
              "score (4-hour EMA in this window) and **contains the contaminated market layer** (D2). "
              "`score_exo` is **reconstructed** from the sub-indices (D5); the served value is null "
              "throughout the window.", ""]
    rows = []
    for ix in INPUT_INDICES:
        v = U[ix]
        b = label_band(v)
        r = {"index": ix + (" (market-affected)" if ix == "composite" else "")}
        for name in BANDS:
            r[name] = pct((b == name).mean())
        r["missing"] = pct(v.isna().mean())
        rows.append(r)
    lines += [md_table(pd.DataFrame(rows), index=False), ""]
    served = int(ticks["score_exo_served"].notna().sum())
    lines.append(f"- Served `score_exo` values in stored window ticks: {served:,} of {len(ticks):,}.")
    lines.append(f"- Ticker-days with confidence below 60: {pct((U['confidence'] < 60).sum() / len(U))} "
                 f"(of valid states: {pct((U.loc[U['state_valid'], 'confidence'] < 60).mean())}).")
    lines.append(f"- Ticker-days with high divergence (spread > 40, computed; D6): "
                 f"{pct(U['div_high'].sum() / len(U))} (of valid states: "
                 f"{pct(U.loc[U['state_valid'], 'div_high'].mean())}).")
    lines.append("")

    lines += ["## Which scoring slot supplied the state (D3, D9)", "",
              "State = last tick stamped before 21:45:00 UTC on the session day. Slot = the tick's "
              "stamp floored to 15 minutes.", ""]
    has = U[U["has_tick"]]
    slot_counts = has["slot"].value_counts().sort_index(ascending=False)
    sc = pd.DataFrame({"ticker-days": slot_counts, "share": (slot_counts / len(has)).map(pct)})
    lines += [md_table(sc), ""]
    lag = has["lag_2130_s"].dropna()
    q = lag.quantile([0, 0.05, 0.25, 0.5, 0.75, 0.95, 0.99, 1.0])
    lines += ["Stamp lag of the 21:30 slot (stamp minus 21:30:00, seconds), over ticker-days that used it:", "",
              md_table(pd.DataFrame({"seconds": q.round(2)}).rename(index=lambda x: f"p{int(x * 100)}")), ""]

    lines += ["### Days where the state did not come from the 21:30 slot", "",
              "Reason per ticker-day (D9): **no 21:30 tick** = no tick in [21:30, 22:00); "
              "**21:30 tick late** = no tick in [21:30, 21:45) but one in [21:45, 22:00); "
              "**no state** = no tick before 21:45 at all.", ""]
    U["reason"] = np.where(~U["has_tick"], "no state",
                  np.where(U["slot"] == "21:30", "21:30 slot",
                  np.where(U["has_late_2130"], "21:30 tick late (>= 21:45)", "no 21:30 tick")))
    rt = U.pivot_table(index="day", columns="reason", values="ticker", aggfunc="count", fill_value=0)
    cols = [c for c in ["21:30 slot", "no 21:30 tick", "21:30 tick late (>= 21:45)", "no state"] if c in rt]
    rt = rt[cols]
    tot = rt.sum().rename("TOTAL")
    lines += [md_table(pd.concat([rt, tot.to_frame().T])), ""]

    # Detail for the non-21:30 days: which slot supplied the state, and tick timing that day.
    nd = U[U["has_tick"] & (U["slot"] != "21:30")].copy()
    if len(nd):
        tk = ticks[ticks["ticker"].isin(used)].copy()
        tk["day"] = tk["ts"].dt.date
        tk = tk[tk["day"].isin(set(nd["day"]))]
        tod_min = tk["ts"].dt.hour * 60 + tk["ts"].dt.minute + tk["ts"].dt.second / 60
        first_after = tk[tod_min >= 21 * 60 + 30].assign(m=tod_min).groupby(["ticker", "day"])["m"].min()
        nd["sel_min"] = nd["ts"].dt.hour * 60 + nd["ts"].dt.minute + nd["ts"].dt.second / 60
        nd = nd.join(first_after.rename("next_min"), on=["ticker", "day"])
        hm = lambda v: "" if pd.isna(v) else f"{int(v // 60):02d}:{int(v % 60):02d}"
        det = nd.pivot_table(index="day", columns="slot", values="ticker", aggfunc="count", fill_value=0)
        det = det[sorted(det.columns, reverse=True)]
        det["selected tick, median stamp"] = nd.groupby("day")["sel_min"].median().map(hm)
        det["selected tick, earliest stamp"] = nd.groupby("day")["sel_min"].min().map(hm)
        det["first tick at/after 21:30, median stamp"] = nd.groupby("day")["next_min"].median().map(hm)
        lines += ["### Detail for days without a 21:30-slot state", "",
                  "Ticker-days by the slot that supplied the state, and tick timing that day (UTC). "
                  "In these early weeks the scoring tick did not run on a fixed 15-minute grid, so "
                  "the late-tick label in D9 describes the stamps, not a known schedule.", "",
                  md_table(det), ""]

    (RESULTS / "coverage.md").write_text("\n".join(lines) + "\n")
    print("wrote results/coverage.md")


if __name__ == "__main__":
    main()
